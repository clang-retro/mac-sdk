/* The two assembly functions of libunwind for 32-bit PowerPC with XCOFF
 * objects (classic Mac OS): __unw_getcontext, which saves the registers,
 * and Registers_ppc::jumpto, which loads them and continues there.
 *
 * libunwind has them in UnwindRegistersSave.S and UnwindRegistersRestore.S,
 * but clang's integrated assembler cannot assemble those files for XCOFF
 * (it does not take the .csect and .toc directives). These are the same
 * instructions as the AIX code there, without the vector registers (the
 * SDK's code does not use AltiVec), as naked functions with inline
 * assembly. The register layout is that of libunwind's Registers_ppc:
 * srr0 (the program counter) at 0, r0 to r31 at 8, cr at 136, lr at 144,
 * ctr at 148 and f0 to f31 at 160.
 *
 * Copyright (C) clang-retro contributors.
 * SPDX-License-Identifier: AGPL-3.0-only */

/* Save the registers of the caller in the context that r3 points to. The
 * program counter is the return address. When the caller is in another
 * code fragment, its glue code changed r2 and the instruction at the
 * return address is "lwz r2,20(r1)": then the caller's r2 is in the
 * stack at 20(r1). Return 0 (UNW_ESUCCESS). */
__attribute__((naked)) int __unw_getcontext(void *context) {
  __asm__ volatile(
      "stw 0, 8(3)\n\t"
      "mflr 0\n\t"
      "stw 0, 0(3)\n\t"
      "stw 1, 12(3)\n\t"
      "stw 4, 24(3)\n\t"
      "mflr 4\n\t"
      "lwz 4, 0(4)\n\t"
      "xoris 0, 4, 0x8041\n\t"
      "cmplwi 0, 0x14\n\t"
      "bne 0, 1f\n\t"
      "lwz 2, 20(1)\n"
      "1:\n\t"
      "stw 2, 16(3)\n\t"
      "stw 3, 20(3)\n\t"
      "stw 5, 28(3)\n\t"
      "stw 6, 32(3)\n\t"
      "stw 7, 36(3)\n\t"
      "stw 8, 40(3)\n\t"
      "stw 9, 44(3)\n\t"
      "stw 10, 48(3)\n\t"
      "stw 11, 52(3)\n\t"
      "stw 12, 56(3)\n\t"
      "stw 13, 60(3)\n\t"
      "stw 14, 64(3)\n\t"
      "stw 15, 68(3)\n\t"
      "stw 16, 72(3)\n\t"
      "stw 17, 76(3)\n\t"
      "stw 18, 80(3)\n\t"
      "stw 19, 84(3)\n\t"
      "stw 20, 88(3)\n\t"
      "stw 21, 92(3)\n\t"
      "stw 22, 96(3)\n\t"
      "stw 23, 100(3)\n\t"
      "stw 24, 104(3)\n\t"
      "stw 25, 108(3)\n\t"
      "stw 26, 112(3)\n\t"
      "stw 27, 116(3)\n\t"
      "stw 28, 120(3)\n\t"
      "stw 29, 124(3)\n\t"
      "stw 30, 128(3)\n\t"
      "stw 31, 132(3)\n\t"
      "mfcr 0\n\t"
      "stw 0, 136(3)\n\t"
      "li 0, 0\n\t"
      "stw 0, 144(3)\n\t"
      "mfctr 0\n\t"
      "stw 0, 148(3)\n\t"
      "stfd 0, 160(3)\n\t"
      "stfd 1, 168(3)\n\t"
      "stfd 2, 176(3)\n\t"
      "stfd 3, 184(3)\n\t"
      "stfd 4, 192(3)\n\t"
      "stfd 5, 200(3)\n\t"
      "stfd 6, 208(3)\n\t"
      "stfd 7, 216(3)\n\t"
      "stfd 8, 224(3)\n\t"
      "stfd 9, 232(3)\n\t"
      "stfd 10, 240(3)\n\t"
      "stfd 11, 248(3)\n\t"
      "stfd 12, 256(3)\n\t"
      "stfd 13, 264(3)\n\t"
      "stfd 14, 272(3)\n\t"
      "stfd 15, 280(3)\n\t"
      "stfd 16, 288(3)\n\t"
      "stfd 17, 296(3)\n\t"
      "stfd 18, 304(3)\n\t"
      "stfd 19, 312(3)\n\t"
      "stfd 20, 320(3)\n\t"
      "stfd 21, 328(3)\n\t"
      "stfd 22, 336(3)\n\t"
      "stfd 23, 344(3)\n\t"
      "stfd 24, 352(3)\n\t"
      "stfd 25, 360(3)\n\t"
      "stfd 26, 368(3)\n\t"
      "stfd 27, 376(3)\n\t"
      "stfd 28, 384(3)\n\t"
      "stfd 29, 392(3)\n\t"
      "stfd 30, 400(3)\n\t"
      "stfd 31, 408(3)\n\t"
      "li 3, 0\n\t"
      "blr");
}

