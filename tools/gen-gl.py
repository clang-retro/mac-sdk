#!/usr/bin/env python3
"""Generate the OpenGL headers and the OpenGL import index.

    python3 tools/gen-gl.py gl.xml

gl.xml is the Khronos OpenGL API registry
(https://github.com/KhronosGroup/OpenGL-Registry, xml/gl.xml). The script
writes:

  - include/GL/gl.h: OpenGL 1.0, 1.1 and 1.2, which Apple OpenGL for the
    classic Mac OS gives.
  - include/GL/glext.h: the extensions that Apple OpenGL 1.2 exports by
    name (the classic Mac OS has no aglGetProcAddress).
  - data/opengl-exports.json: the functions of the shared libraries
    OpenGLLibrary (gl* and agl*) and OpenGLUtility (glu*), read from
    the headers. tools/link/gen-imports.py adds it to imports.json.

include/GL/glu.h and include/AGL/agl.h are written by hand; this script
only reads them.

Copyright (C) clang-retro contributors.
SPDX-License-Identifier: AGPL-3.0-only
"""
import json
import os
import re
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

VERSIONS = ["GL_VERSION_1_0", "GL_VERSION_1_1", "GL_VERSION_1_2"]

# The extensions of Apple OpenGL 1.2 for the classic Mac OS, and the
# ones that Windows programs of the time examine with glGetString. A
# function that the library does not have is a weak import: it is NULL.
EXTENSIONS = ["GL_ARB_multitexture", "GL_ARB_transpose_matrix",
              "GL_EXT_compiled_vertex_array", "GL_EXT_abgr", "GL_EXT_bgra",
              "GL_EXT_vertex_array", "GL_EXT_paletted_texture",
              "GL_APPLE_transform_hint", "GL_ARB_texture_env_add",
              "GL_ARB_texture_cube_map", "GL_EXT_blend_color",
              "GL_EXT_blend_minmax", "GL_EXT_blend_subtract",
              "GL_EXT_texture_lod_bias", "GL_EXT_texture_filter_anisotropic",
              "GL_SGIS_generate_mipmap", "GL_SGIS_texture_edge_clamp"]

# Names that the old gl.h of Windows and of Apple have and that the
# registry no longer puts in a feature.
OLD_ENUMS = {"GL_LOGIC_OP": "0x0BF1", "GL_TEXTURE_COMPONENTS": "0x1003"}

HEAD = """\
/* {name} - {what}
 *
 * Generated by tools/gen-gl.py from the Khronos OpenGL API registry
 * (gl.xml, Copyright 2013-2026 The Khronos Group Inc.,
 * SPDX-License-Identifier: Apache-2.0). Do not edit.
 *
 * Part of mac-sdk.
 */
"""


def text_of(elem):
    """Give the text of an XML element and its children, with the
    <apientry/> markers as APIENTRY."""
    out = elem.text or ""
    for c in elem:
        out += ("APIENTRY" if c.tag == "apientry" else text_of(c))
        out += c.tail or ""
    return out


def load(path):
    """Read gl.xml: give its enums by name, its commands by name and its
    features and extensions by name."""
    reg = ET.parse(path).getroot()
    enums = {}
    for group in reg.findall("enums"):
        for e in group.findall("enum"):
            if e.get("api") not in (None, "gl"):
                continue
            enums.setdefault(e.get("name"), e.get("value"))
    commands = {}
    for c in reg.find("commands").findall("command"):
        proto = c.find("proto")
        name = proto.find("name").text
        ret = text_of(proto).strip()
        ret = ret[:ret.rfind(name)].strip()
        params = [" ".join(text_of(p).split()) for p in c.findall("param")]
        commands[name] = (ret, params)
    parts = {}
    for f in reg.findall("feature"):
        if f.get("api") == "gl":
            parts[f.get("name")] = f
    for e in reg.find("extensions").findall("extension"):
        parts[e.get("name")] = e
    return enums, commands, parts


def required(part):
    """Give the enums and commands that a feature or extension requires,
    in registry order, for the compatibility profile of desktop GL."""
    es, cs = [], []
    for req in part.findall("require"):
        if req.get("api") not in (None, "gl"):
            continue
        if req.get("profile") not in (None, "compatibility"):
            continue
        es += [e.get("name") for e in req.findall("enum")]
        cs += [c.get("name") for c in req.findall("command")]
    return es, cs


def emit(out, title, part_names, enums, commands, parts, seen_e, seen_c):
    """Write the #defines and prototypes of the features or extensions in
    part_names to out, each name once. Give the command names written."""
    written = []
    for pn in part_names:
        es, cs = required(parts[pn])
        out.append(f"\n#ifndef {pn}\n#define {pn} 1")
        for e in es:
            if e in seen_e or e not in enums:
                continue
            seen_e.add(e)
            out.append(f"#define {e} {enums[e]}")
        for c in cs:
            if c in seen_c:
                continue
            seen_c.add(c)
            ret, params = commands[c]
            out.append(f"GLAPI {ret} APIENTRY {c}({', '.join(params) or 'void'});")
            written.append(c)
        if title == "ext":
            for c in cs:
                ret, params = commands[c]
                out.append(f"typedef {ret} (APIENTRY *PFN{c.upper()}PROC)"
                           f"({', '.join(params) or 'void'});")
        out.append(f"#endif /* {pn} */")
    return written


GL_TYPES = """
typedef unsigned int GLenum;
typedef unsigned char GLboolean;
typedef unsigned int GLbitfield;
typedef void GLvoid;
typedef signed char GLbyte;
typedef short GLshort;
typedef int GLint;
typedef unsigned char GLubyte;
typedef unsigned short GLushort;
typedef unsigned int GLuint;
typedef int GLsizei;
typedef float GLfloat;
typedef float GLclampf;
typedef double GLdouble;
typedef double GLclampd;
"""


def write_gl(enums, commands, parts):
    """Write include/GL/gl.h and include/GL/glext.h. Give the names of the
    functions they declare."""
    seen_e, seen_c = set(), set()
    gl = [HEAD.format(name="gl.h", what="OpenGL 1.2, as Apple OpenGL for "
                      "the classic Mac OS gives it.\n *\n * The functions "
                      "are in the shared library OpenGLLibrary, which the "
                      "linker\n * imports weakly: on a Mac without OpenGL "
                      "they are NULL. Test\n * (void *)glBegin before the "
                      "first call. PowerPC only: Apple OpenGL has\n * no "
                      "68k version."),
          "#ifndef __gl_h_\n#define __gl_h_\n#define __GL_H__",
          "\n#ifndef APIENTRY\n#define APIENTRY\n#endif"
          "\n#ifndef APIENTRYP\n#define APIENTRYP APIENTRY *\n#endif"
          "\n#ifndef WINGDIAPI\n#define WINGDIAPI\n#endif"
          "\n/* Weak on PowerPC, so that a program can test a function for NULL.\n"
          " * On 68k there is no OpenGL: a call does not link. */"
          "\n#ifndef GLAPI\n#if defined(__powerpc__) || defined(__POWERPC__)"
          "\n#define GLAPI extern __attribute__((weak))\n#else"
          "\n#define GLAPI extern\n#endif\n#endif",
          "\n#ifdef __cplusplus\nextern \"C\" {\n#endif",
          GL_TYPES.rstrip()]
    names = emit(gl, "core", VERSIONS, enums, commands, parts, seen_e, seen_c)
    gl.append("\n/* Old names that the gl.h of the time had. */")
    for k, v in OLD_ENUMS.items():
        gl.append(f"#ifndef {k}\n#define {k} {v}\n#endif")
    gl.append("\n#ifdef __cplusplus\n}\n#endif")
    gl.append("\n#include <GL/glext.h>\n\n#endif /* __gl_h_ */\n")

    ext = [HEAD.format(name="glext.h", what="the OpenGL extensions that "
                       "Apple OpenGL 1.2 for the classic Mac OS\n * exports "
                       "by name. glGetString(GL_EXTENSIONS) tells which "
                       "ones the\n * renderer has; the functions of an "
                       "extension that the library\n * does not export "
                       "are NULL (weak imports)."),
           "#ifndef __glext_h_\n#define __glext_h_",
           "\n#include <GL/gl.h>",
           "\n#ifdef __cplusplus\nextern \"C\" {\n#endif",
           "\n#define GL_GLEXT_VERSION 1"]
    names += emit(ext, "ext", [e for e in EXTENSIONS if e in parts], enums,
                  commands, parts, seen_e, seen_c)
    ext.append("\n#ifdef __cplusplus\n}\n#endif\n\n#endif /* __glext_h_ */\n")

    os.makedirs(os.path.join(ROOT, "include", "GL"), exist_ok=True)
    for fn, lines in (("gl.h", gl), ("glext.h", ext)):
        with open(os.path.join(ROOT, "include", "GL", fn), "w") as f:
            f.write("\n".join(lines))
    return names


def declared(path, prefix):
    """Give the names of the functions that start with prefix and that the
    header at path declares."""
    text = open(path).read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return sorted(set(re.findall(r"\b(" + prefix + r"[A-Z]\w*)\s*\(", text)) -
                  {n for n in re.findall(r"\(\s*\w*\s*\*\s*(" + prefix +
                                         r"\w*)\s*\)", text)})


def main():
    """Read gl.xml and write the headers and the import index."""
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    enums, commands, parts = load(sys.argv[1])
    gl_names = write_gl(enums, commands, parts)
    agl = declared(os.path.join(ROOT, "include", "AGL", "agl.h"), "agl")
    glu = declared(os.path.join(ROOT, "include", "GL", "glu.h"), "glu")
    libs = {"OpenGLLibrary": {"func": sorted(gl_names + agl), "data": [],
                              "weak": True},
            "OpenGLUtility": {"func": glu, "data": [], "weak": True}}
    with open(os.path.join(ROOT, "data", "opengl-exports.json"), "w") as f:
        json.dump(libs, f, indent=1, sort_keys=True)
        f.write("\n")
    print(f"gl: {len(gl_names)} functions, agl: {len(agl)}, glu: {len(glu)}")


if __name__ == "__main__":
    main()
